// The dialogue library.
//
// Every line here is authored, not generated: the point of the system is that the street
// answers differently depending on who you are and what it has heard, so the *choice* of
// line is dynamic while the words themselves stay hand-written and in one voice.
//
// The pools are keyed by intent (what the player did) x depth (first exchange or follow-up)
// x mood band (how the character feels about you right now). Five intents, two depths,
// three bands, three lines each — plus a per-character voice pack that gets spliced in so
// the same intent still sounds like *this* person and not a generic NPC.

